-- Literary knowledge canon (Vietnam + international) for student workspace
-- Apply: mysql -u root -p diemdanh_literature < database/literary_canon.sql

SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS `literary_work` (
  `id` int NOT NULL AUTO_INCREMENT,
  `title` varchar(255) NOT NULL COMMENT 'Display title',
  `title_original` varchar(255) DEFAULT NULL COMMENT 'Original language title if different',
  `author` varchar(255) NOT NULL,
  `author_original` varchar(255) DEFAULT NULL,
  `region` enum('vietnam','international') NOT NULL DEFAULT 'vietnam',
  `country` varchar(80) DEFAULT NULL COMMENT 'e.g. Vietnam, France, USA',
  `genre` enum('poem','story','novel','drama','essay','epic') NOT NULL DEFAULT 'story',
  `genre_label` varchar(60) DEFAULT NULL,
  `era` varchar(80) DEFAULT NULL,
  `language` varchar(40) DEFAULT 'Vietnamese',
  `excerpt` text,
  `description` text,
  `keywords` text COMMENT 'Space-separated search keywords',
  `cover_image` varchar(500) DEFAULT NULL COMMENT 'Poster/cover URL or site-relative path',
  `wikipedia_url` varchar(500) DEFAULT NULL,
  `featured` tinyint(1) NOT NULL DEFAULT 0,
  `sort_order` int NOT NULL DEFAULT 0,
  `created_at` datetime DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  KEY `idx_lw_region` (`region`),
  KEY `idx_lw_genre` (`genre`),
  KEY `idx_lw_featured` (`featured`),
  FULLTEXT KEY `ft_lw_search` (`title`,`author`,`keywords`,`description`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

